export type TranslationKey = keyof typeof dictionaries.zh;
type TranslationParams = Record<string, string | number>;

function initialLanguage(): Language {
  if (typeof globalThis.localStorage?.getItem !== "function") return "zh";
  return globalThis.localStorage.getItem(STORAGE_KEY) === "en" ? "en" : "zh";
}

interface I18nState {
  language: Language;
  setLanguage: (language: Language) => void;
}

export const useI18nStore = create<I18nState>((set) => ({
  language: initialLanguage(),
  setLanguage: (language) => {
    if (typeof globalThis.localStorage?.setItem === "function") {
      globalThis.localStorage.setItem(STORAGE_KEY, language);
    }
    if (typeof document !== "undefined") {
      document.documentElement.lang = language === "zh" ? "zh-CN" : "en";
    }
    set({ language });
  },
}));

export function translate(
  key: TranslationKey,
  language: Language,
  params?: TranslationParams,
): string {
  const template = dictionaries[language][key] ?? dictionaries.zh[key];
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.hasOwn(params, name) ? String(params[name]) : match,
  );
}

export function t(key: TranslationKey, params?: TranslationParams): string {
  return translate(key, useI18nStore.getState().language, params);
}

export function useTranslation() {
  const language = useI18nStore((state) => state.language);
  const setLanguage = useI18nStore((state) => state.setLanguage);
  const translateForLanguage = useCallback(
    (key: TranslationKey, params?: TranslationParams) =>
      translate(key, language, params),
    [language],
  );
  return {
    language,
    setLanguage,
    t: translateForLanguage,
  };
}
